import java.io.FileInputStream
import java.util.Properties

// Modulo de aplicacion ParFMI.
// Firma de release opcional: si existe keystore.properties en la raiz se usa
// esa clave; en caso contrario se firma con la clave de depuracion (instalable
// pero NO valida como firma de produccion).
plugins {
    id("com.android.application")
    id("org.jetbrains.kotlin.android")
    id("org.jetbrains.kotlin.plugin.compose")
    id("org.jetbrains.kotlin.plugin.serialization")
}

val keystorePropsFile = rootProject.file("keystore.properties")
val keystoreProps = Properties().apply {
    if (keystorePropsFile.exists()) {
        FileInputStream(keystorePropsFile).use { load(it) }
    }
}

android {
    namespace = "com.andrespar2.parfmi"
    compileSdk = 35

    defaultConfig {
